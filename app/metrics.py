"""Prometheus metrics. One uvicorn worker per pod, so the default registry is enough:
Prometheus scrapes every pod and Grafana sums across them."""

from prometheus_client import Counter, Gauge, Histogram

LATENCY_BUCKETS = (0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2, 4, 8, 15, 30, 60)

REQUESTS = Counter(
    "gateway_requests_total",
    "Chat completion requests handled by the gateway",
    ["model", "provider", "status", "cache"],
)
REQUEST_LATENCY = Histogram(
    "gateway_request_duration_seconds",
    "End-to-end latency seen by the client",
    ["model", "cache"],
    buckets=LATENCY_BUCKETS,
)
UPSTREAM_LATENCY = Histogram(
    "gateway_upstream_duration_seconds",
    "Latency of a single upstream call",
    ["provider", "upstream_model"],
    buckets=LATENCY_BUCKETS,
)
UPSTREAM_ATTEMPTS = Counter(
    "gateway_upstream_attempts_total",
    "Upstream call attempts by outcome",
    ["provider", "outcome"],
)
FALLBACKS = Counter(
    "gateway_fallbacks_total",
    "Requests served by a provider other than the first target",
    ["model", "provider"],
)
TOKENS = Counter(
    "gateway_tokens_total",
    "Tokens sent to / generated by upstream providers",
    ["provider", "upstream_model", "kind"],
)
COST = Counter(
    "gateway_cost_usd_total",
    "Spend on upstream providers in USD",
    ["provider", "upstream_model"],
)
CACHE_LOOKUPS = Counter(
    "gateway_cache_lookups_total",
    "Cache lookups by result",
    ["result"],
)
CACHE_SAVED_TOKENS = Counter(
    "gateway_cache_saved_tokens_total",
    "Tokens not sent upstream thanks to the cache",
    ["kind"],
)
CACHE_SAVED_USD = Counter(
    "gateway_cache_saved_usd_total",
    "Upstream spend avoided by cache hits (local models priced at their reference model)",
    ["model"],
)
RATE_LIMITED = Counter(
    "gateway_rate_limited_total",
    "Requests rejected by per-key limits",
    ["key", "reason"],
)
CIRCUIT_OPEN = Gauge(
    "gateway_circuit_open",
    "1 while the circuit breaker for a provider is open",
    ["provider"],
)
